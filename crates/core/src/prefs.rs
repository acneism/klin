#[derive(Clone, Copy, Debug, PartialEq)]
pub enum PrefDefault {
    Bool(bool),
    Int(i64),
    String(&'static str),
}

impl PrefDefault {
    pub fn value(self) -> PrefValue {
        match self {
            PrefDefault::Bool(b) => PrefValue::Bool(b),
            PrefDefault::Int(i) => PrefValue::Int(i),
            PrefDefault::String(s) => PrefValue::String(s.to_owned()),
        }
    }
}

const PREFS_JS_HEADER: &str = "// Mozilla User Preferences\n\n// DO NOT EDIT THIS FILE.\n//\n\
// If you make changes to this file while the application is running,\n\
// the changes will be overwritten when the application exits.\n//\n\
// To change a preference value, you can either:\n\
// - modify it via the UI (e.g. via about:config in the browser); or\n\
// - set it within a user.js file in your profile.\n\n";

#[derive(Clone, Debug, PartialEq)]
pub enum PrefValue {
    Bool(bool),
    Int(i64),
    String(String),
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct UserPrefs {
    values: std::collections::HashMap<String, PrefValue>,
}

impl UserPrefs {
    pub fn parse_files(texts: &[&str]) -> Self {
        let mut prefs = Self::default();
        for text in texts {
            for (name, value) in parse(text) {
                prefs.values.insert(name, value);
            }
        }
        prefs
    }

    pub fn get(&self, name: &str) -> Option<&PrefValue> {
        self.values.get(name)
    }

    pub fn set(&mut self, name: &str, value: PrefValue) {
        let default = KNOWN
            .iter()
            .find(|(n, _)| *n == name)
            .map(|(_, d)| d.value());
        if default.as_ref() == Some(&value) {
            self.values.remove(name);
        } else {
            self.values.insert(name.to_owned(), value);
        }
    }

    pub fn reset(&mut self, name: &str) {
        self.values.remove(name);
    }

    pub fn is_user_set(&self, name: &str) -> bool {
        self.values.contains_key(name)
    }

    pub fn value_or_default(&self, name: &str) -> Option<PrefValue> {
        self.values.get(name).cloned().or_else(|| {
            KNOWN
                .iter()
                .find(|(n, _)| *n == name)
                .map(|(_, d)| d.value())
        })
    }

    pub fn names(&self) -> Vec<String> {
        let mut names: Vec<String> = KNOWN.iter().map(|(n, _)| (*n).to_owned()).collect();
        names.extend(self.values.keys().cloned());
        names.sort();
        names.dedup();
        names
    }

    pub fn string(&self, name: &str, default: &str) -> String {
        match self.get(name) {
            Some(PrefValue::String(v)) => v.clone(),
            _ => default.to_owned(),
        }
    }

    pub fn homepage(&self) -> String {
        self.string(HOMEPAGE_PREF, HOMEPAGE)
    }

    pub fn bookmarks_toolbar(&self) -> String {
        self.string(BOOKMARKS_TOOLBAR, "newtab")
    }

    pub fn known_bool(&self, name: &str) -> bool {
        matches!(self.value_or_default(name), Some(PrefValue::Bool(true)))
    }

    pub fn content_blocking_strict(&self) -> bool {
        self.string(CONTENT_BLOCKING_CATEGORY, "standard") == "strict"
    }

    pub fn history_enabled(&self) -> bool {
        self.bool(HISTORY_ENABLED, true)
    }

    pub fn to_prefs_js(&self) -> String {
        let mut names: Vec<&String> = self.values.keys().collect();
        names.sort();
        let mut out = PREFS_JS_HEADER.to_owned();
        for name in names {
            let value = match &self.values[name] {
                PrefValue::Bool(b) => b.to_string(),
                PrefValue::Int(i) => i.to_string(),
                PrefValue::String(s) => quote(s),
            };
            out.push_str(&format!("user_pref({}, {value});\n", quote(name)));
        }
        out
    }

    pub fn int(&self, name: &str, default: i64) -> i64 {
        match self.get(name) {
            Some(PrefValue::Int(v)) => *v,
            _ => default,
        }
    }

    pub fn bool(&self, name: &str, default: bool) -> bool {
        match self.get(name) {
            Some(PrefValue::Bool(v)) => *v,
            _ => default,
        }
    }

    pub fn startup_page(&self) -> i64 {
        self.int(STARTUP_PAGE, 1)
    }

    pub fn resume_from_crash(&self) -> bool {
        self.bool(RESUME_FROM_CRASH, true)
    }
}

fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn parse(text: &str) -> Vec<(String, PrefValue)> {
    let text = strip_comments(text);
    let mut out = Vec::new();
    let mut rest = text.as_str();
    while let Some(start) = rest.find("pref(") {
        let call = &rest[start + 5..];
        let Some(end) = call.find(");") else { break };
        let args = &call[..end];
        rest = &call[end + 2..];
        let Some((name, value)) = split_args(args) else {
            continue;
        };
        if let Some(value) = parse_value(value.trim()) {
            out.push((name, value));
        }
    }
    out
}

fn strip_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut chars = text.chars().peekable();
    let mut in_string = false;
    while let Some(c) = chars.next() {
        if in_string {
            out.push(c);
            if c == '\\' {
                if let Some(n) = chars.next() {
                    out.push(n);
                }
            } else if c == '"' {
                in_string = false;
            }
            continue;
        }
        match (c, chars.peek()) {
            ('"', _) => {
                in_string = true;
                out.push(c);
            }
            ('/', Some('/')) | ('#', _) => {
                for n in chars.by_ref() {
                    if n == '\n' {
                        out.push('\n');
                        break;
                    }
                }
            }
            ('/', Some('*')) => {
                chars.next();
                let mut prev = ' ';
                for n in chars.by_ref() {
                    if prev == '*' && n == '/' {
                        break;
                    }
                    prev = n;
                }
            }
            _ => out.push(c),
        }
    }
    out
}

fn split_args(args: &str) -> Option<(String, &str)> {
    let args = args.trim();
    let (name, after) = parse_string(args)?;
    let value = after.trim_start().strip_prefix(',')?;
    Some((name, value))
}

fn parse_string(s: &str) -> Option<(String, &str)> {
    let s = s.strip_prefix('"')?;
    let mut out = String::new();
    let mut chars = s.char_indices();
    while let Some((i, c)) = chars.next() {
        match c {
            '\\' => {
                let (_, n) = chars.next()?;
                out.push(match n {
                    'n' => '\n',
                    't' => '\t',
                    other => other,
                });
            }
            '"' => return Some((out, &s[i + 1..])),
            c => out.push(c),
        }
    }
    None
}

fn parse_value(v: &str) -> Option<PrefValue> {
    match v {
        "true" => Some(PrefValue::Bool(true)),
        "false" => Some(PrefValue::Bool(false)),
        _ if v.starts_with('"') => parse_string(v).map(|(s, _)| PrefValue::String(s)),
        _ => v.parse().ok().map(PrefValue::Int),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_firefox_prefs_js() {
        let prefs_js = r#"// Mozilla User Preferences
/* Do not edit this file. */
user_pref("browser.startup.page", 3);
user_pref("browser.startup.homepage", "https://servo.org/;https://e.com/\"q\"");
user_pref("browser.sessionstore.resume_from_crash", false);
user_pref("app.update.lastUpdateTime.background", -1700000000); // trailing
"#;
        let user_js = "# comment\nuser_pref(\"browser.startup.page\", 1);\n";
        let p = UserPrefs::parse_files(&[prefs_js]);
        assert_eq!(p.startup_page(), 3);
        assert!(!p.resume_from_crash());
        assert_eq!(
            p.get("browser.startup.homepage"),
            Some(&PrefValue::String(
                "https://servo.org/;https://e.com/\"q\"".into()
            ))
        );
        assert_eq!(
            p.int("app.update.lastUpdateTime.background", 0),
            -1700000000
        );
        assert_eq!(
            UserPrefs::parse_files(&[prefs_js, user_js]).startup_page(),
            1
        );
        assert_eq!(UserPrefs::default().startup_page(), 1);
        assert!(UserPrefs::default().resume_from_crash());
    }

    #[test]
    fn writes_prefs_js_that_reads_back() {
        let mut p = UserPrefs::default();
        p.set(STARTUP_PAGE, PrefValue::Int(3));
        p.set(
            HOMEPAGE_PREF,
            PrefValue::String("https://e.com/\"q\"\\x".into()),
        );
        p.set(HISTORY_ENABLED, PrefValue::Bool(true));
        assert!(!p.is_user_set(HISTORY_ENABLED));
        let text = p.to_prefs_js();
        assert!(text.starts_with("// Mozilla User Preferences"));
        assert!(text.contains("user_pref(\"browser.startup.page\", 3);"));
        assert_eq!(UserPrefs::parse_files(&[&text]), p);
        p.reset(STARTUP_PAGE);
        assert_eq!(p.startup_page(), 1);
    }
}
